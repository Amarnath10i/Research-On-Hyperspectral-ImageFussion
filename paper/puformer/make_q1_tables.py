    for _, _, modes in COND_MODELS:
        rules.append(f"\\cmidrule(lr){{{c0}-{c0 + len(modes) - 1}}}")
        c0 += len(modes)
    return head1, "".join(rules), " & ".join(MODE_LAB[m] for _, _, m in cols)


