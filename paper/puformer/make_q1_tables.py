ALL = METHODS[:-1] + NEW + METHODS[-1:]                          # PUFormer last
# (key, label, decimals, higher is better)
SHORT = [("PSNR", "PSNR", 2, True), ("SSIM", "SSIM", 4, True), ("SAM", "SAM", 3, False), ("ERGAS", "ERGAS", 3, False)]
