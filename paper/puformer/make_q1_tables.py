def significance():
    """Paired Wilcoxon signed-rank test of per-image PSNR, PUFormer vs the best other method, per setting."""
    try:
        from scipy.stats import wilcoxon
    except ImportError:
        return
    wins = total = 0
    for ds, (_, scales) in DATASETS.items():
        for s in scales:
            p = load(f"bench-{ds}-x{s}-puformer")
            others = [(m, load(f"bench-{ds}-x{s}-{m}")) for m in BASELINES]
            others = [(m, r) for m, r in others if r]
            if not p or not others:
                continue
            m, b = max(others, key=lambda x: x[1]["test"]["PSNR"])
            a = [x["PSNR"] for x in p["test_per_image"]]
            c = [x["PSNR"] for x in b["test_per_image"]]
            total += 1
            wins += all(x > y for x, y in zip(a, c))
            pv = wilcoxon(a, c, alternative="greater").pvalue if len(a) >= 5 else float("nan")
            NUM[f"{ds}{s}-p"] = f"{pv:.4f}" if pv == pv else "--"
            NUM[f"{ds}{s}-best-other"] = dict((k, v) for k, v, _ in ALL)[m]
            NUM[f"{ds}{s}-nimg"] = str(len(a))
            NUM[f"{ds}{s}-allwin"] = "all" if all(x > y for x, y in zip(a, c)) else \
                f"{sum(x > y for x, y in zip(a, c))} of {len(a)}"
    NUM["settings-allwin"], NUM["settings-total"] = str(wins), str(total)


